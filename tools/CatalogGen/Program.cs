using System.Globalization;
using System.Text;
using DBUDoctor.Core;
using DBUDoctor.Core.Config;
using DBUDoctor.Core.Pricing;
using DBUDoctor.Core.Pricing.Aws;
using DBUDoctor.Core.Pricing.Azure;
using DBUDoctor.Core.Pricing.Databricks;

namespace DBUDoctor.CatalogGen;

/// <summary>
/// Regenerates the generated parts of the catalog:
/// - catalog/prices/azure/&lt;armRegionName&gt;.yaml from the Azure Retail Prices API;
/// - catalog/prices/{aws,gcp}/&lt;region&gt;.yaml and catalog/node-types/{aws,gcp}.yaml from the
///   Databricks pricing calculator data, plus AWS VM prices from the AWS Price List bulk files.
/// Usage: CatalogGen [--catalog &lt;dir&gt;] [--clouds azure,aws,gcp] [--regions a,b] [--as-of yyyy-MM-dd] [--summary &lt;file&gt;]
/// (--regions applies to Azure.)
/// </summary>
public static class Program
{
    public const string Header =
        "Generated by tools/CatalogGen from the Azure Retail Prices API. Do not edit by hand:\n" +
        "change the generator or its inputs and regenerate. Premium DBU meters, Linux VMs only.\n" +
        "VM columns are $/hour; reservations are the term price divided by the hours in the term.";

    public static async Task<int> Main(string[] args)
    {
        var catalogDir = Path.GetFullPath("catalog");
        string[]? regions = null;
        var asOf = DateOnly.FromDateTime(DateTime.UtcNow);
        string? summaryPath = null;
        var clouds = new[] { "azure", "aws", "gcp" };

        for (var i = 0; i < args.Length; i++)
        {
            switch (args[i])
            {
                case "--catalog": catalogDir = Path.GetFullPath(args[++i]); break;
                case "--regions": regions = args[++i].Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries); break;
                case "--as-of": asOf = DateOnly.ParseExact(args[++i], "yyyy-MM-dd", CultureInfo.InvariantCulture); break;
                case "--summary": summaryPath = args[++i]; break;
                case "--clouds": clouds = args[++i].Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries); break;
                default:
                    Console.Error.WriteLine($"Unknown argument: {args[i]}");
                    return 2;
            }
        }

        try
        {
            using var http = new HttpClient { Timeout = TimeSpan.FromMinutes(2) };
            http.DefaultRequestHeaders.UserAgent.ParseAdd("DBUDoctor-CatalogGen/1.0");

            // A region's EC2 price list is a few hundred MB, streamed.
            using var bulk = new HttpClient { Timeout = TimeSpan.FromMinutes(30) };
            bulk.DefaultRequestHeaders.UserAgent.ParseAdd("DBUDoctor-CatalogGen/1.0");
            var result = new StringBuilder();
            result.Append("## Catalog refresh ").Append(asOf.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture)).Append("\n\n");
            if (clouds.Contains("azure"))
            {
                result.Append(await GenerateAsync(new AzureRetailPricesClient(http), catalogDir, regions, asOf, Console.Error).ConfigureAwait(false)).Append('\n');
            }

            foreach (var cloud in new[] { Cloud.Aws, Cloud.Gcp }.Where(c => clouds.Contains(EnumNames.Of(c))))
            {
                var aws = cloud == Cloud.Aws ? new AwsPriceListClient(bulk) : null;
                result.Append(await GenerateDatabricksAsync(new DatabricksPricingClient(http), cloud, catalogDir, asOf, Console.Error, aws).ConfigureAwait(false)).Append('\n');
            }

            if (summaryPath is not null)
            {
                await File.WriteAllTextAsync(summaryPath, result.ToString()).ConfigureAwait(false);
            }

            return 0;
        }
        catch (Exception ex) when (ex is DoctorException or HttpRequestException or System.Text.Json.JsonException)
        {
            Console.Error.WriteLine(ex.Message);
            return 2;
        }
    }

    /// <summary>Writes one file per region and returns a Markdown summary of the price changes.</summary>
    public static async Task<string> GenerateAsync(AzureRetailPricesClient client, string catalogDir, IReadOnlyCollection<string>? regions, DateOnly asOf, TextWriter log)
    {
        var catalog = CatalogLoader.LoadDirectory(catalogDir);
        var vmTypes = new HashSet<string>(catalog.NodeTypesFor(Cloud.Azure)?.NodeTypes.Keys ?? [], StringComparer.Ordinal);
        if (catalog.Warehouses.VmLayouts.TryGetValue(Cloud.Azure, out var layouts))
        {
            foreach (var layout in layouts.Values)
            {
                vmTypes.Add(layout.Driver);
                vmTypes.Add(layout.Worker);
            }
        }

        var provenance = new Provenance(asOf, AzureRetailPricesClient.Endpoint);
        log.WriteLine("Fetching Azure Databricks meters…");
        var allDbu = await client.DatabricksMetersAsync(null).ConfigureAwait(false);
        var byRegion = allDbu
            // Real regions only: armRegionName values such as "Global" or "US Gov" are pricing zones.
            .Where(i => !string.IsNullOrEmpty(i.ArmRegionName) && i.ArmRegionName.All(c => char.IsAsciiLetterLower(c) || char.IsAsciiDigit(c)))
            .GroupBy(i => i.ArmRegionName!, StringComparer.Ordinal)
            .ToDictionary(g => g.Key, g => g.ToList(), StringComparer.Ordinal);

        var targetRegions = (regions ?? byRegion.Keys.ToArray()).Order(StringComparer.Ordinal).ToList();
        var outDir = Path.Combine(catalogDir, "prices", "azure");
        Directory.CreateDirectory(outDir);

        var summary = new StringBuilder();
        summary.Append("### Azure\n\n");
        var unmappedAll = new SortedSet<string>(StringComparer.Ordinal);

        foreach (var region in targetRegions)
        {
            if (!byRegion.TryGetValue(region, out var dbuItems))
            {
                log.WriteLine($"{region}: no Azure Databricks meters, skipped.");
                continue;
            }

            log.WriteLine($"{region}: fetching VM meters…");
            var vmItems = await client.VirtualMachineMetersAsync(region).ConfigureAwait(false);
            var result = AzurePriceNormalizer.Normalize(region, dbuItems, vmItems, vmTypes, provenance);
            foreach (var meter in result.UnmappedPremiumMeters)
            {
                unmappedAll.Add(meter);
            }

            if (result.Sheet.Dbu.Count == 0)
            {
                log.WriteLine($"{region}: no Premium DBU prices, skipped.");
                continue;
            }

            var path = Path.Combine(outDir, region + ".yaml");
            var previous = File.Exists(path) ? CatalogLoader.ParsePriceSheet($"prices/azure/{region}.yaml", await File.ReadAllTextAsync(path).ConfigureAwait(false)) : null;
            await File.WriteAllTextAsync(path, AzurePriceNormalizer.ToYaml(result.Sheet, provenance, Header)).ConfigureAwait(false);
            AppendChanges(summary, region, previous, result.Sheet);
            log.WriteLine($"{region}: {result.Sheet.Dbu.Count} DBU prices, {result.Sheet.Vm.Count} VM types.");
        }

        if (unmappedAll.Count > 0)
        {
            summary.Append("\n### Premium DBU meters without a mapping\n\nAdd them to `AzurePriceNormalizer.MeterToSku` or `IgnoredPremiumMeters`:\n\n");
            foreach (var meter in unmappedAll)
            {
                summary.Append("- ").Append(meter).Append('\n');
                log.WriteLine($"warning: unmapped Premium DBU meter: {meter}");
            }
        }

        return summary.ToString();
    }

    public const string AwsHeader =
        "Generated by tools/CatalogGen from the Databricks pricing calculator data (DBU) and the AWS Price List\n" +
        "bulk files (VMs). Do not edit by hand: change the generator or its inputs and regenerate.\n" +
        "dbu is the Premium plan, dbu_enterprise the Enterprise plan (pricing.tier). VM columns are $/hour for\n" +
        "Linux, shared tenancy: payg is On-Demand, reserved_1y and reserved_3y are Standard, No Upfront.";

    public const string DatabricksHeader =
        "Generated by tools/CatalogGen from the Databricks pricing calculator data. Do not edit by hand:\n" +
        "change the generator or its inputs and regenerate. DBU prices only: the catalog has no VM prices for this cloud.\n" +
        "dbu is the Premium plan, dbu_enterprise the Enterprise plan (pricing.tier).";

    /// <summary>AWS or GCP: one price file per region and the node-type table, replacing the previous files.</summary>
    public static async Task<string> GenerateDatabricksAsync(DatabricksPricingClient client, Cloud cloud, string catalogDir, DateOnly asOf, TextWriter log, AwsPriceListClient? aws = null)
    {
        var name = EnumNames.Of(cloud);
        log.WriteLine($"Fetching the Databricks pricing data for {EnumNames.Display(cloud)}…");
        var rows = await client.RowsAsync(cloud).ConfigureAwait(false);
        var provenance = new Provenance(asOf, DatabricksPricingClient.UrlFor(cloud));
        var result = DatabricksPricingNormalizer.Normalize(cloud, rows, provenance);
        if (result.Regions.Count == 0 || result.NodeTypes.Count == 0)
        {
            throw new DoctorException($"The {EnumNames.Display(cloud)} pricing data produced no regions or no node types; its layout may have changed. Nothing was written.");
        }

        var summary = new StringBuilder();
        summary.Append("### ").Append(EnumNames.Display(cloud)).Append("\n\n");
        var outDir = Path.Combine(catalogDir, "prices", name);
        Directory.CreateDirectory(outDir);
        var previous = Directory.GetFiles(outDir, "*.yaml").ToDictionary(
            f => Path.GetFileNameWithoutExtension(f),
            f => CatalogLoader.ParsePriceSheet($"prices/{name}/{Path.GetFileName(f)}", File.ReadAllText(f)),
            StringComparer.Ordinal);
        foreach (var stale in previous.Keys.Where(r => !result.Regions.ContainsKey(r)))
        {
            File.Delete(Path.Combine(outDir, stale + ".yaml"));
            summary.Append("- `").Append(stale).Append("`: removed (no longer in the pricing data)\n");
        }

        var vmNotes = new List<string>();
        var vmConflicts = new List<string>();
        IReadOnlyDictionary<string, string>? csvUrls = null;
        if (aws is not null)
        {
            log.WriteLine("Fetching the AWS Price List region index…");
            csvUrls = await aws.RegionCsvUrlsAsync().ConfigureAwait(false);
        }

        var instanceTypes = result.NodeTypes.Keys.ToHashSet(StringComparer.Ordinal);
        foreach (var (region, dbuSheet) in result.Regions)
        {
            var sheet = dbuSheet;
            if (aws is not null)
            {
                if (csvUrls!.TryGetValue(region, out var url))
                {
                    log.WriteLine($"Reading EC2 prices for {region}…");
                    var vm = await AwsPriceListNormalizer.NormalizeAsync(aws.RecordsAsync(url), instanceTypes).ConfigureAwait(false);
                    var vmProvenance = new Provenance(asOf, AwsPriceListClient.RegionIndexUrl);
                    sheet = new PriceSheet
                    {
                        Cloud = dbuSheet.Cloud,
                        Region = dbuSheet.Region,
                        Currency = dbuSheet.Currency,
                        Dbu = dbuSheet.Dbu,
                        DbuEnterprise = dbuSheet.DbuEnterprise,
                        Vm = vm.Prices
                            .Where(kv => kv.Value.ContainsKey(Commitment.Payg))
                            .ToDictionary(kv => kv.Key, kv => new VmPrice(kv.Value, vmProvenance), StringComparer.Ordinal),
                        VmProvenance = vmProvenance,
                    };
                    vmConflicts.AddRange(vm.Conflicts.Select(c => $"{region}: {c}"));
                    var missing = instanceTypes.Count(t => !sheet.Vm.ContainsKey(t));
                    if (missing > 0)
                    {
                        vmNotes.Add($"{region}: {sheet.Vm.Count} of {instanceTypes.Count} instance types priced; {missing} not offered there");
                    }
                }
                else
                {
                    vmNotes.Add($"{region}: not in the AWS Price List region index, so no VM prices");
                }
            }

            var header = aws is not null && sheet.Vm.Count > 0 ? AwsHeader : DatabricksHeader;
            await File.WriteAllTextAsync(Path.Combine(outDir, region + ".yaml"), CatalogWriter.Prices(sheet, provenance, header)).ConfigureAwait(false);
            AppendChanges(summary, region, previous.GetValueOrDefault(region), sheet);
        }

        Section(summary, "VM price coverage", vmNotes, log);
        Section(summary, "VM prices left out because the AWS Price List lists conflicting values", vmConflicts, log);

        var nodePath = Path.Combine(catalogDir, "node-types", name + ".yaml");
        var nodeCount = File.Exists(nodePath) ? File.ReadLines(nodePath).Count(l => l.StartsWith("  ", StringComparison.Ordinal) && l.Contains("{ dbu:", StringComparison.Ordinal)) : 0;
        Directory.CreateDirectory(Path.GetDirectoryName(nodePath)!);
        await File.WriteAllTextAsync(nodePath, CatalogWriter.NodeTypes(cloud, result.NodeTypes, provenance, DatabricksHeader.Split('\n')[0] + "\nDBU per hour per instance type (Premium classic rows); Photon counts from the \"(Photon)\" rows.")).ConfigureAwait(false);
        summary.Append("- node types: ").Append(nodeCount).Append(" → ").Append(result.NodeTypes.Count).Append('\n');
        log.WriteLine($"{EnumNames.Display(cloud)}: {result.Regions.Count} regions, {result.NodeTypes.Count} node types.");

        Section(summary, "Values left out because the data lists conflicting prices", result.Conflicts, log);
        Section(summary, "Workloads without a mapping (add them to `DatabricksPricingNormalizer.ComputeToSku` or `IgnoredComputes`)", result.UnmappedComputes, log);
        Section(summary, "Regions without a code (add them to `DatabricksPricingNormalizer.RegionCodes`)", result.UnmappedRegions, log);
        return summary.ToString();
    }

    private static void Section(StringBuilder summary, string title, IReadOnlyList<string> items, TextWriter log)
    {
        if (items.Count == 0)
        {
            return;
        }

        summary.Append("\n").Append(title).Append(":\n\n");
        foreach (var item in items)
        {
            summary.Append("- ").Append(item).Append('\n');
            log.WriteLine($"warning: {title.Split(' ')[0]}: {item}");
        }
    }

    private static void AppendChanges(StringBuilder summary, string region, PriceSheet? previous, PriceSheet current)
    {
        if (previous is null)
        {
            summary.Append("- `").Append(region).Append("`: new region\n");
            return;
        }

        var lines = new List<string>();
        foreach (var (tier, label) in new[] { (PlanTier.Premium, ""), (PlanTier.Enterprise, " (Enterprise)") })
        {
            var before = previous.DbuFor(tier);
            var after = current.DbuFor(tier);
            foreach (var sku in before.Keys.Union(after.Keys).Order(StringComparer.Ordinal))
            {
                var b = before.TryGetValue(sku, out var bv) ? bv.Value.ToString(CultureInfo.InvariantCulture) : "—";
                var a = after.TryGetValue(sku, out var av) ? av.Value.ToString(CultureInfo.InvariantCulture) : "—";
                if (b != a)
                {
                    lines.Add($"  - {sku}{label}: {b} → {a} $/DBU");
                }
            }
        }

        var vmChanges = previous.Vm.Keys.Union(current.Vm.Keys).Count(type =>
            !previous.Vm.TryGetValue(type, out var p) || !current.Vm.TryGetValue(type, out var c) ||
            !p.Columns.OrderBy(x => x.Key).SequenceEqual(c.Columns.OrderBy(x => x.Key)));
        if (vmChanges > 0)
        {
            lines.Add($"  - {vmChanges} VM type(s) changed price");
        }

        if (lines.Count > 0)
        {
            summary.Append("- `").Append(region).Append("`\n");
            foreach (var line in lines)
            {
                summary.Append(line).Append('\n');
            }
        }
    }
}
